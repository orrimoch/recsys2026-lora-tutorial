# A 2-3 sentence reply (or a small JSON in structured mode) needs only a few
# hundred tokens; the cap is a runaway guard, NOT a latency knob (unused tokens
# cost nothing). With thinking off it never truncates a real reply.
MAX_OUTPUT_TOKENS = int(os.environ.get("GEMINI_MAX_OUTPUT_TOKENS", "1024"))
# 0 = thinking DISABLED. The gemini-2.5 models otherwise spend their whole output
# budget "thinking" and return finish_reason=STOP with NO answer Part, so `.text`
# raises and every row falls back. Disabling it both fixes that and is far faster.
THINKING_BUDGET = int(os.environ.get("GEMINI_THINKING_BUDGET", "0"))


class GenModel:
    """Adapter exposing the legacy `model.generate_content(prompt, generation_config=...)`
    surface on top of the modern google-genai client, with THINKING DISABLED and a hard
    `max_output_tokens` cap. This is the fix for the gemini-2.5 failure where the model
    spends its whole budget thinking, returns finish_reason=STOP with no answer Part, and
    `.text` raises (-> every row fell back). thinking_budget=0 is valid for flash /
    flash-lite; pro cannot fully disable thinking, so a 0 is clamped to its 128 minimum.

    Keeping this surface identical to the old genai.GenerativeModel means _call_model /
    generate_response / generate_best_of_n and all their tests are untouched."""

    def __init__(self, client, types, model, max_output_tokens=MAX_OUTPUT_TOKENS,
                 thinking_budget=THINKING_BUDGET):
        self.client, self.types, self.model = client, types, model
        self.max_output_tokens = max_output_tokens
        # pro can't run with a 0 budget; bump a requested 0 to the 128 floor for it.
        self.thinking_budget = (128 if thinking_budget == 0 and "pro" in model.lower()
                                else thinking_budget)

    def generate_content(self, prompt, generation_config=None):
        gc = generation_config or {}
        t = self.types
        cfg = t.GenerateContentConfig(
            max_output_tokens=self.max_output_tokens,
            temperature=gc.get("temperature"),
            thinking_config=t.ThinkingConfig(thinking_budget=self.thinking_budget),
        )
        return self.client.models.generate_content(
            model=self.model, contents=prompt, config=cfg)


def _resp_cache_path(cache_dir: str, prompt: str, model: str, best_of: int,
                     cache_salt: str = "") -> Path:
    """Cache key = (prompt, model, best_of, cache_salt). The prompt already encodes ctx
    + the rendered tracks + goal + top_n + plain/structured mode; best_of changes
    generation. cache_salt carries the generation knobs the prompt does NOT encode
    (thinking_budget, temperature config) — without it a thinking/temp retune reads
    STALE replies from a warm cache and an A/B looks flat (bug #10)."""
    key = "\n".join([prompt, str(model), str(best_of), str(cache_salt)])
    h = hashlib.sha1(key.encode("utf-8")).hexdigest()[:24]
    return Path(cache_dir) / f"{h}.json"


def load_reuse_map(path) -> dict:
    """Map {(session_id, turn_number): {'ids': [...], 'resp': str}} from a PRIOR
    prediction.json — to warm-start responses so only changed rows hit Gemini.
    Accepts a .json file OR a .zip (reads its `prediction.json` member, e.g. a saved
    submission on Drive). Missing / empty path -> {}."""
    if not path:
        return {}
    if str(path).endswith(".zip"):
        import zipfile
        with zipfile.ZipFile(path) as z:
            member = next((n for n in z.namelist() if n.endswith("prediction.json")), None)
            if member is None:
                raise ValueError(f"{path}: no prediction.json inside the zip")
            rows = json.loads(z.read(member))
    else:
        with open(path, encoding="utf-8") as f:
            rows = json.load(f)
    m: dict = {}
    for r in rows:
        m[(r.get("session_id"), r.get("turn_number"))] = {
            "ids": r.get("predicted_track_ids") or [],
            "resp": r.get("predicted_response") or "",
        }
    return m


def reuse_response(reuse_map: dict, session_id, turn_number, track_ids, top_n: int):
    """Prior response IFF the responder-visible tracks (the top_n shown) are unchanged
    vs the prior run, else None. ctx + goal are deterministic from (session_id,
    turn_number), so identical shown-tracks => identical responder input => safe reuse.
    (Pass a reuse file produced by the SAME responder config: model / top_n / best_of.)"""
    prior = reuse_map.get((session_id, turn_number))
    if not prior or not prior["resp"]:
        return None
    if list(prior["ids"][:top_n]) == list((track_ids or [])[:top_n]):
        return prior["resp"]
    return None


def cached_response(cache_dir, prompt: str, model: str, best_of: int,
                    gen_fn, fallback: str, cache_salt: str = "") -> str:
    """Disk-cache the responder output so reruns don't re-pay Gemini. `gen_fn()`
    returns the freshly generated response. A FALLBACK (generation failed -> kept
    the original) is NOT cached, so a fixed API/key regenerates next run (the same
    rule the listwise reranker uses for empty parses). cache_dir falsy -> no cache.
    cache_salt keys generation knobs not in the prompt (thinking_budget/temperature)
    so a retune doesn't read stale replies (bug #10)."""
    cp = None
    if cache_dir:
        cp = _resp_cache_path(cache_dir, prompt, model, best_of, cache_salt)
        if cp.exists():
            try:
                return json.loads(cp.read_text(encoding="utf-8"))["response"]
            except (OSError, json.JSONDecodeError, KeyError, ValueError):
                pass
    resp = gen_fn()
    if cp is not None and resp and resp != fallback:
        cp.parent.mkdir(parents=True, exist_ok=True)
        cp.write_text(json.dumps({"response": resp}, ensure_ascii=False),
                      encoding="utf-8")
    return resp
